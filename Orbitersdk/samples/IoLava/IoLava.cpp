namespace
{
	struct Source
	{
		enum Kind { TOES, LAKE, SKYLIGHT } kind = TOES;
		VECTOR3 pos{};             // vessel frame (x east, y up, z north)
		double a = 1, tone = 0.5, rgb[3] = { 1, 0.1, 0 };
		double logL = 0;           // log10 of the mean luminance
		double x = 0, burst = 0;   // flicker state [dex]
		double k = 1;              // current intensity factor
		LightEmitter* le = nullptr;
	};
	struct Sublim { VECTOR3 pos{}; int light = -1; double lvl = 0; PSTREAM_HANDLE ps = nullptr; };
	struct GlowGroup { int group = 0; int kind = 0; };

	double gLo = std::log10(0.00722), gHi = std::log10(4228.0);
	double Tone(double logL) { return std::pow(std::clamp((logL - gLo) / (gHi - gLo), 0.0, 1.0), 0.3); }

	// relaxation time [s], wander [dex], events per s, event jump [dex], event fade [s]
	struct Flicker { double tau, sigma, rate, jump, fade; };
	const Flicker FL[3] = {
		{ 25.0, 0.12, 1.0 / 40, 0.35, 15.0 },   // front toes: crust tears, new toes break out every ~minute
		{ 6.0, 0.08, 1.0 / 300, 0.50, 40.0 },   // lava lake: plates drift; now and then the crust founders
		{ 2.0, 0.05, 0.0, 0.0, 1.0 },           // skylight: the stream below churns
	};
}

class LavaField : public VESSEL3
{
public:
	LavaField(OBJHANDLE h, int fm) : VESSEL3(h, fm), rng_(std::random_device{}()) {}

	void clbkSetClassCaps(FILEHANDLE cfg) override
	{
		char kind[32] = {};
		if (oapiReadItem_string(cfg, const_cast<char*>("Kind"), kind) && !_stricmp(kind, "Plume")) { plume_ = true; PlumeCaps(); return; }
		if (!_stricmp(kind, "Vent")) { vent_ = true; VentCaps(); return; }
		SetSize(2.0);   // NOT bigger: Orbiter then serves the whole area coarse (level-10) elevation and the crew sinks into the relief
		SetEmptyMass(1000.0);
		SetPMI(_V(1, 1, 1));
		SetCrossSections(_V(0.01, 0.01, 0.01));
		Load("Config\\Io\\LavaField\\Effects.cfg");
		const double m = 1000.0, k = m * 1.8 / 0.003, c = 2 * std::sqrt(k * m);
		TOUCHDOWNVTX t[3] = { { _V(0, 0, 1), k, c, 3, 3 }, { _V(-0.87, 0, -0.5), k, c, 3, 3 }, { _V(0.87, 0, -0.5), k, c, 3, 3 } };
		if (td_.size() == 3) for (int i = 0; i < 3; ++i) t[i].pos = td_[i];
		SetTouchdownPoints(t, 3);
		for (Source& s : src_)
		{
			const double b = s.tone > 0 ? 2.0 * std::pow(s.tone, 0.3) : 0;
			COLOUR4 dif = { float(s.rgb[0] * b), float(s.rgb[1] * b), float(s.rgb[2] * b), 0 }, spc = dif, amb = { 0, 0, 0, 0 };
			s.le = AddPointLight(s.pos, (s.kind == Source::LAKE ? 5.0 : 6.0) * s.a,   // beyond ~6 A the disc gives < 3 %
				1.0, 0.0, 1.0 / (s.a * s.a), dif, spc, amb);
		}
		// SO2 frost turned to gas at the front leaves ballistically (no air to stop it), carrying frost grains lit from
		// below by the lava. Few and small: a handful of particles per second per source. The texture lies in the
		// Textures root (like Tantra_dust): round, alpha falling to 0 at the edge - the particle shader blends by alpha.
		SURFHANDLE tex = oapiRegisterParticleTexture(const_cast<char*>("IoLava_sublim"));
		for (Sublim& u : sub_)
		{
			// jets: grains thrown up at ~15 m/s (the gas itself is far faster and invisible), narrow, a few seconds
			PARTICLESTREAMSPEC ps = { 0, 0.4, 12.0, 15.0, 0.05, 5.0, 0.6, 0.0, PARTICLESTREAMSPEC::EMISSIVE,   // srcspread: a FRACTION of v0
				PARTICLESTREAMSPEC::LVL_LIN, 0, 1, PARTICLESTREAMSPEC::ATM_FLAT, 1, 1, tex };
			u.ps = AddParticleStream(&ps, u.pos, _V(0, 1, 0), &u.lvl);
		}
		if (!meshName_.empty())
		{
			MESHHANDLE mh = oapiLoadMeshGlobal(meshName_.c_str());
			if (mh) { meshIdx_ = AddMesh(mh); SetMeshVisibilityMode(meshIdx_, MESHVIS_ALWAYS); }
			else oapiWriteLogV("IoLava: mesh %s not found", meshName_.c_str());
		}
		if (!plumeMesh_.empty())
		{
			MESHHANDLE ph = oapiLoadMeshGlobal(plumeMesh_.c_str());
			if (ph) { plumeIdx_ = AddMesh(ph); SetMeshVisibilityMode(plumeIdx_, MESHVIS_ALWAYS); }
			oapiWriteLogV("IoLava: Prometheus plume as a mesh of this vessel: %s, %d bands", ph ? plumeMesh_.c_str() : "NOT FOUND", (int)pbands_.size());
		}
		if (!skinMesh_.empty())
		{
			MESHHANDLE sh = oapiLoadMeshGlobal(skinMesh_.c_str());
			if (sh) { skinIdx_ = AddMesh(sh); SetMeshVisibilityMode(skinIdx_, MESHVIS_ALWAYS); }
			oapiWriteLogV("IoLava: lobe skin %s", sh ? skinMesh_.c_str() : "NOT FOUND");
		}
		if (!fpMesh_.empty())
		{
			MESHHANDLE fh = oapiLoadMeshGlobal(fpMesh_.c_str());
			if (fh) { fpIdx_ = AddMesh(fh); SetMeshVisibilityMode(fpIdx_, MESHVIS_ALWAYS); }
			fpOk_ = field_.Load("Config\\Io\\LavaField\\LavaField.cfg");
			slots_.assign(fpN_, Slot{});
			oapiWriteLogV("IoLava: footprints %s, %d slots, rasters %s", fh ? fpMesh_.c_str() : "NOT FOUND", fpN_, fpOk_ ? "ok" : "NOT LOADED");
		}
		oapiWriteLogV("IoLava: %d light sources, %d sublimation sources (texture %s), glow mesh %s (%d groups), %s touchdown",
			(int)src_.size(), (int)sub_.size(), tex ? "IoLava_sublim ok" : "IoLava_sublim NOT LOADED",
			meshName_.empty() ? "-" : meshName_.c_str(), (int)glow_.size(), td_.size() == 3 ? "terrain" : "default");
	}

	void clbkVisualCreated(VISHANDLE vis, int) override { vis_ = vis; }
	void clbkVisualDestroyed(VISHANDLE, int) override { vis_ = nullptr; }

	void clbkPreStep(double, double simdt, double) override
	{
		const double dt = std::clamp(simdt, 0.0, 2.0);
		if (dt <= 0) return;
		if (plume_) { PlumeStep(dt); return; }
		if (vent_) { NearOnly(meshIdx_, dt); return; }
		simT_ += dt;
		if ((probePass_ == 0 && simT_ > 15) || (probePass_ == 1 && simT_ > 45)) { ++probePass_; LogProbes(); }
		std::normal_distribution<double> N(0, 1);
		std::uniform_real_distribution<double> U(0, 1);
		for (Source& s : src_)
		{
			const Flicker& f = FL[s.kind];
			s.x += -s.x / f.tau * dt + f.sigma * std::sqrt(2 * dt / f.tau) * N(rng_);
			s.burst *= std::exp(-dt / f.fade);
			if (f.rate > 0 && U(rng_) < f.rate * dt) s.burst += f.jump;
			const double base = Tone(s.logL);
			s.k = base > 0 ? Tone(s.logL + s.x + s.burst) / base : 1.0;
			if (s.le) s.le->SetIntensity(s.k);
		}
		for (Sublim& u : sub_)   // the hotter the toes next to it, the more frost goes
			u.lvl = std::clamp(0.10 * (u.light >= 0 ? src_[u.light].k : 1.0), 0.0, 0.25);
		dayTimer_ -= dt;
		if (dayTimer_ <= 0) { dayTimer_ = 5.0; const double e = SunElev(), t = std::clamp(e / (20 * RAD), 0.0, 1.0); dayK_ = 1.0 - 0.75 * t * t * (3 - 2 * t); }
		PlumeLight(dt);
		Footprints(dt);
		NearOnly(skinIdx_, dt);
		if (!vis_ || meshIdx_ == (UINT)-1) return;
		DEVMESHHANDLE dm = GetDevMesh(vis_, meshIdx_);
		if (!dm) return;
		for (const GlowGroup& g : glow_)
		{
			double k = 0; int n = 0;
			for (const Source& s : src_) if ((int)s.kind == g.kind) { k += s.k; ++n; }
			k = (n ? k / n : 1.0) * dayK_ * glowGain_;
			if (g.kind == 0 && skinIdx_ != (UINT)-1) k = 0;   // the opaque lobe skin shows the lobe now: no double cracks   // > 1: past the post-process glare threshold (1.1)
			const oapi::FVECTOR4 c(float(k), float(k), float(k), 1.0f);
			oapiSetMaterialEx(dm, g.group, MatProp::Diffuse, &c);
			oapiSetMaterialEx(dm, g.group, MatProp::Light, &c);
		}
	}

private:
	std::vector<Source> src_;
	std::vector<Sublim> sub_;
	std::vector<GlowGroup> glow_;
	std::vector<VECTOR3> td_;
	struct Probe { std::string name; double lng, lat, l17; };
	std::vector<Probe> probes_;
	double simT_ = 0; int probePass_ = 0;
	std::string meshName_;
	UINT meshIdx_ = (UINT)-1;
	VISHANDLE vis_ = nullptr;
	double dayTimer_ = 0, dayK_ = 1, glowGain_ = 1;
	std::mt19937 rng_;

	// ---------------------------------------------------------------- the Prometheus plume (Kind = Plume)
	bool plume_ = false;
	struct Band { int group; double h; };
	std::vector<Band> bands_;
	double pBase_ = 0.3, pG_ = 0.5, pKmax_ = 1.6, pR_ = 1.821e6, pTimer_ = 0;

	void PlumeCaps()
	{
		SetSize(160e3);                 // the canopy reaches 160 km from the vent
		SetEmptyMass(1000.0);
		SetPMI(_V(1, 1, 1));
		SetCrossSections(_V(0.01, 0.01, 0.01));
		FILE* f = std::fopen("Config\\Io\\LavaField\\Plume.cfg", "r");
		if (!f) { oapiWriteLog(const_cast<char*>("IoLava: Plume.cfg not found")); return; }
		char line[256], name[256];
		while (std::fgets(line, sizeof line, f))
		{
			double e, n, u, v; int g;
			if (std::sscanf(line, "TOUCHDOWN %lf %lf %lf", &e, &n, &u) == 3) td_.push_back(_V(e, u, n));
			else if (std::sscanf(line, "BAND %d %lf", &g, &v) == 2) bands_.push_back({ g, v });
			else if (std::sscanf(line, "BASE %lf", &v) == 1) pBase_ = v;
			else if (std::sscanf(line, "HG_G %lf", &v) == 1) pG_ = v;
			else if (std::sscanf(line, "KMAX %lf", &v) == 1) pKmax_ = v;
			else if (std::sscanf(line, "RADIUS %lf", &v) == 1) pR_ = v;
			else if (std::sscanf(line, "MESH %255s", name) == 1) meshName_ = name;
		}
		std::fclose(f);
		const double m = 1000.0, k = m * 1.8 / 0.003, c = 2 * std::sqrt(k * m);
		TOUCHDOWNVTX t[3] = { { _V(0, 0, 1000), k, c, 3, 3 }, { _V(-866, 0, -500), k, c, 3, 3 }, { _V(866, 0, -500), k, c, 3, 3 } };
		if (td_.size() == 3) for (int i = 0; i < 3; ++i) t[i].pos = td_[i];
		SetTouchdownPoints(t, 3);
		MESHHANDLE mh = meshName_.empty() ? nullptr : oapiLoadMeshGlobal(meshName_.c_str());
		if (mh) { meshIdx_ = AddMesh(mh); SetMeshVisibilityMode(meshIdx_, MESHVIS_ALWAYS); }
		oapiWriteLogV("IoLava: Prometheus plume, mesh %s, %d bands", mh ? meshName_.c_str() : "NOT FOUND", (int)bands_.size());
	}

	void PlumeStep(double dt)
	{
		pTimer_ -= dt;
		if (pTimer_ > 0 || !vis_ || meshIdx_ == (UINT)-1) return;
		pTimer_ = 0.5;
		DEVMESHHANDLE dm = GetDevMesh(vis_, meshIdx_);
		OBJHANDLE sun = oapiGetGbodyByIndex(0);
		if (!dm || !sun) return;
		VECTOR3 sp, cp; oapiGetGlobalPos(sun, &sp); oapiCameraGlobalPos(&cp);
		const double el = SunElev();
		auto hg = [&](double c) { const double g = pG_; return (1 - g * g) / std::pow(1 + g * g - 2 * g * c, 1.5); };
		const double p90 = hg(0.0);
		for (const Band& b : bands_)
		{
			// sunlit when the Sun stands above the dip of the horizon seen from height h
			const double dip = -std::acos(pR_ / (pR_ + b.h)), t = std::clamp((el - dip) / (1.0 * RAD) + 0.5, 0.0, 1.0);
			VECTOR3 bp; Local2Global(_V(0, b.h, 0), bp);
			const double cs = dotp(unit(bp - sp), unit(cp - bp));         // 1 = looking at the Sun through the plume
			const double k = (std::min)(pKmax_, pBase_ * hg(cs) / p90) * t * t * (3 - 2 * t);
			const oapi::FVECTOR4 c(float(k), float(k), float(k), 1.0f);   // each band has its own material
			oapiSetMaterialEx(dm, b.group, MatProp::Diffuse, &c);
			oapiSetMaterialEx(dm, b.group, MatProp::Light, &c);
		}
	}


	// diagnostic: the ground the crew walks on (Orbiter core) against the ground D3D9Client draws, at fixed points
	void LogProbes()
	{
		OBJHANDLE ref = GetSurfaceRef();
		if (!ref) return;
		gcCore2* gc = gcGetCoreInterface();
		HPLANETMGR pm = gc ? gc->GetPlanetManager(ref) : nullptr;
		for (const Probe& p : probes_)
		{
			int lvl = -1;
			const double lng = p.lng * RAD, lat = p.lat * RAD;
			const double core = oapiSurfaceElevationEx(ref, lng, lat, 0, nullptr, nullptr, &lvl);
			double rend = -99999; int rl = -1;
			if (pm) { gcCore::PickGround pg = gc->GetTileData(pm, lng, lat, -1); if (pg.hTile) { rend = pg.elev; rl = pg.level; } }
			oapiWriteLogV("IoLava probe %d %-16s core %8.2f m (lvl %d)  render %8.2f m (tile lvl %d)  tiles L17 %8.2f m",
				probePass_, p.name.c_str(), core, lvl, rend, rl, p.l17);
		}
	}

	// the Prometheus plume (second mesh): each height band lit when the Sun clears the horizon seen from its height,
	// brightness by forward scattering of small grains (Henyey-Greenstein) towards the camera
	struct PBand { int group; double h; VECTOR3 pos; };
	std::vector<PBand> pbands_;
	std::string plumeMesh_;
	UINT plumeIdx_ = (UINT)-1;
	double plTimer_ = 0;
	void PlumeLight(double dt)
	{
		plTimer_ -= dt;
		if (plTimer_ > 0 || !vis_ || plumeIdx_ == (UINT)-1) return;
		plTimer_ = 0.5;
		DEVMESHHANDLE dm = GetDevMesh(vis_, plumeIdx_);
		OBJHANDLE sun = oapiGetGbodyByIndex(0), ref = GetSurfaceRef();
		if (!dm || !sun || !ref) return;
		VECTOR3 sp, cp, cc; oapiGetGlobalPos(sun, &sp); oapiCameraGlobalPos(&cp); oapiGetGlobalPos(ref, &cc);
		auto hg = [&](double c) { const double g = pG_; return (1 - g * g) / std::pow(1 + g * g - 2 * g * c, 1.5); };
		const double p90 = hg(0.0);
		for (const PBand& b : pbands_)
		{
			VECTOR3 bp; Local2Global(b.pos, bp);
			const double el = std::asin(std::clamp(dotp(unit(bp - cc), unit(sp - bp)), -1.0, 1.0));   // Sun over the band's horizon plane
			const double dip = -std::acos(pR_ / (pR_ + b.h)), t = std::clamp((el - dip) / (1.0 * RAD) + 0.5, 0.0, 1.0);
			const double cs = dotp(unit(bp - sp), unit(cp - bp));                                     // 1 = looking at the Sun through it
			const double k = (std::min)(pKmax_, pBase_ * hg(cs) / p90) * t * t * (3 - 2 * t);
			const oapi::FVECTOR4 c(float(k), float(k), float(k), 1.0f);
			oapiSetMaterialEx(dm, b.group, MatProp::Diffuse, &c);
			oapiSetMaterialEx(dm, b.group, MatProp::Light, &c);
		}
	}

	// ---------------------------------------------------------------- the summit pit lining (Kind = Vent)
	bool vent_ = false;
	void VentCaps()
	{
		SetSize(2.0); SetEmptyMass(1000.0); SetPMI(_V(1, 1, 1)); SetCrossSections(_V(0.01, 0.01, 0.01));
		FILE* f = std::fopen("Config\\Io\\LavaField\\Vent.cfg", "r");
		char line[256], name[256];
		while (f && std::fgets(line, sizeof line, f))
		{
			double e, n, u;
			if (std::sscanf(line, "TOUCHDOWN %lf %lf %lf", &e, &n, &u) == 3) td_.push_back(_V(e, u, n));
			else if (std::sscanf(line, "MESH %255s", name) == 1) meshName_ = name;
		}
		if (f) std::fclose(f);
		const double m = 1000.0, k = m * 1.8 / 0.003, c = 2 * std::sqrt(k * m);
		TOUCHDOWNVTX t[3] = { { _V(0, 0, 30), k, c, 3, 3 }, { _V(-26, 0, -15), k, c, 3, 3 }, { _V(26, 0, -15), k, c, 3, 3 } };
		if (td_.size() == 3) for (int i = 0; i < 3; ++i) t[i].pos = td_[i];
		SetTouchdownPoints(t, 3);
		MESHHANDLE mh = meshName_.empty() ? nullptr : oapiLoadMeshGlobal(meshName_.c_str());
		if (mh) { meshIdx_ = AddMesh(mh); SetMeshVisibilityMode(meshIdx_, MESHVIS_ALWAYS); }
		oapiWriteLogV("IoLava: summit pit lining %s", mh ? meshName_.c_str() : "NOT FOUND");
	}

	// ---------------------------------------------------------------- footprints through thin crust
	// A boot that breaks a crust thinner than ~2 cm (2..5 cm: by chance) opens the melt under it (1450 K); the hole skins
	// over and cools like any new surface (cooling.py): yellow, orange, red, gone in ~30 min. The colour is a texture strip
	// along u = log(age); the module moves quads of one mesh under the crew's feet.
	struct Slot { bool on = false; double lng = 0, lat = 0, hdg = 0, born = 0; };
	struct Walker { double lng = 0, lat = 0, acc = 0; int foot = 0; bool init = false; };
	lava::Field field_;
	bool fpOk_ = false;
	std::string fpMesh_, skinMesh_;
	UINT skinIdx_ = (UINT)-1;
	UINT fpIdx_ = (UINT)-1;
	int fpN_ = 64, fpNext_ = 0;
	double fpAgeMax_ = 1800, fpThrLo_ = 0.02, fpThrHi_ = 0.05, fpTimer_ = 0, simNow_ = 0;
	std::vector<Slot> slots_;
	std::map<OBJHANDLE, Walker> walkers_;

	void Footprints(double dt)
	{
		simNow_ += dt;
		fpTimer_ -= dt;
		if (fpTimer_ > 0 || !fpOk_ || fpIdx_ == (UINT)-1) return;
		fpTimer_ = 0.1;
		OBJHANDLE ref = GetSurfaceRef();
		if (!ref) return;
		const double R = oapiGetSize(ref);
		// 1. steps of the crew on the field
		for (DWORD i = 0; i < oapiGetVesselCount(); ++i)
		{
			OBJHANDLE h = oapiGetVesselByIndex(i);
			VESSEL* v = oapiGetVesselInterface(h);
			if (!v || !std::strstr(v->GetClassNameA(), "OrbiterCrew\\Astronavigator")) continue;
			if (v->GetSurfaceRef() != ref || v->GetAltitude() > 2.5) continue;
			double lng, lat, rad; v->GetEquPos(lng, lat, rad);
			Walker& w = walkers_[h];
			if (!w.init) { w = { lng, lat, 0, 0, true }; continue; }
			const double dn = (lat - w.lat) * R, de = (lng - w.lng) * R * std::cos(lat);
			w.acc += std::hypot(dn, de); w.lng = lng; w.lat = lat;
			if (w.acc < 0.55) continue;                       // one step
			w.acc = 0; w.foot ^= 1;
			double hdg = 0; oapiGetHeading(h, &hdg);
			const double side = w.foot ? 0.12 : -0.12;          // left / right boot, across the heading
			const double fe = side * std::cos(hdg), fn = -side * std::sin(hdg);
			const double flat = lat + fn / R, flng = lng + fe / (R * std::cos(lat));
			// the suit's own rule (CrewMember.dll, 2026-10-18): sampled at the crew position, deterministic per 0.25 m cell,
			// so a print appears exactly where the suit breaks through
			lava::Sample sm;
			const double latD = lat * DEG, lngD = lng * DEG;
			if (!field_.At(latD, lngD, sm) || !sm.lava) continue;
			const double c = sm.crustM;
			const double sx = std::sin(std::floor(latD / 7.866e-6) * 12.9898 + std::floor(lngD / 7.870e-6) * 78.233) * 43758.5453;
			const double uu = sx - std::floor(sx);
			const double p = std::clamp((fpThrHi_ - c) / (fpThrHi_ - fpThrLo_), 0.0, 1.0);
			const bool through = sm.kind == 6 || c < fpThrLo_ || (c < fpThrHi_ && uu < p);
			if (!through) continue;
			slots_[fpNext_] = { true, flng, flat, hdg, simNow_ };
			fpNext_ = (fpNext_ + 1) % (int)slots_.size();
		}
		// 2. the mesh: each slot a 0.34 x 0.18 m hole along its heading, coloured by its age
		if (!vis_) return;
		DEVMESHHANDLE dm = GetDevMesh(vis_, fpIdx_);
		if (!dm) return;
		std::vector<NTVERTEX> vt(4 * slots_.size());
		const double umax = std::log10(fpAgeMax_);
		for (size_t k = 0; k < slots_.size(); ++k)
		{
			Slot& s = slots_[k];
			const double age = simNow_ - s.born;
			if (s.on && age > fpAgeMax_) s.on = false;
			NTVERTEX* q = &vt[4 * k];
			for (int j = 0; j < 4; ++j) { q[j] = NTVERTEX{}; q[j].y = -1000; q[j].ny = 1; }
			if (!s.on) continue;
			const double u = std::clamp(std::log10((std::max)(age, 1.0)) / umax, 0.0, 1.0);
			const double ch = std::cos(s.hdg), sh = std::sin(s.hdg);
			const double L = 0.17, W = 0.09;
			const double off[4][2] = { { -L, -W }, { L, -W }, { L, W }, { -L, W } };   // heel-left, toe-left, toe-right, heel-right
			const double elev = oapiSurfaceElevation(ref, s.lng, s.lat) + 0.03;
			for (int j = 0; j < 4; ++j)
			{
				const double fwd = off[j][0], rt = off[j][1];
				const double n = fwd * ch - rt * sh, e = fwd * sh + rt * ch;      // heading: from north towards east
				VECTOR3 g, l;
				oapiEquToGlobal(ref, s.lng + e / (R * std::cos(s.lat)), s.lat + n / R, R + elev, &g);
				Global2Local(g, l);
				q[j].x = float(l.x); q[j].y = float(l.y); q[j].z = float(l.z);
				q[j].tu = float(u); q[j].tv = (j == 0 || j == 1) ? 0.0f : 1.0f;
			}
		}
		GROUPEDITSPEC ges{};
		ges.flags = GRPEDIT_VTXCRD | GRPEDIT_VTXTEX;
		ges.Vtx = vt.data(); ges.nVtx = (DWORD)vt.size(); ges.vIdx = nullptr;
		oapiEditMeshGroup(dm, 0, &ges);
	}

	// an opaque lining lies on the exact (level-17) ground; from far away D3D9Client draws the terrain coarser and it
	// pokes through. Far off the terrain tiles show the lava anyway: the lining only near the camera.
	double nearTimer_ = 0; int nearState_ = -1;
	void NearOnly(UINT idx, double dt)
	{
		if (idx == (UINT)-1) return;
		nearTimer_ -= dt;
		if (nearTimer_ > 0) return;
		nearTimer_ = 0.5;
		VECTOR3 c, p; oapiCameraGlobalPos(&c); GetGlobalPos(p);
		const int on = length(c - p) < 350.0 ? 1 : 0;
		if (on != nearState_) { SetMeshVisibilityMode(idx, on ? MESHVIS_ALWAYS : MESHVIS_NEVER); nearState_ = on; }
	}

	double SunElev() const   // [rad]: daylight fades the glow in over 0..20 deg (low Sun lights the ground weakly)
	{
		OBJHANDLE ref = GetSurfaceRef(), sun = oapiGetGbodyByIndex(0);
		if (!ref || !sun) return -1;
		VECTOR3 p, c, s;
		GetGlobalPos(p); oapiGetGlobalPos(ref, &c); oapiGetGlobalPos(sun, &s);
		return std::asin(std::clamp(dotp(unit(p - c), unit(s - p)), -1.0, 1.0));
	}

	void Load(const char* path)
	{
		FILE* f = std::fopen(path, "r");
		if (!f) { oapiWriteLogV("IoLava: %s not found - no effects", path); return; }
		char line[512];
		int lastToes = -1;
		while (std::fgets(line, sizeof line, f))
		{
			char kind[32] = {}, name[256] = {};
			double e, n, u, a, lum, tone, r, g, b, lo, hi;
			int gi;
			if (std::sscanf(line, "TONE_RANGE %lf %lf", &lo, &hi) == 2 && lo > 0 && hi > lo) { gLo = std::log10(lo); gHi = std::log10(hi); }
			else if (std::sscanf(line, "LIGHT %31s %lf %lf %lf A %lf LUM %lf TONE %lf RGB %lf %lf %lf",
				kind, &e, &n, &u, &a, &lum, &tone, &r, &g, &b) == 10)
			{
				Source s;
				s.kind = !std::strcmp(kind, "LAKE") ? Source::LAKE : !std::strcmp(kind, "SKYLIGHT") ? Source::SKYLIGHT : Source::TOES;
				s.pos = _V(e, u, n); s.a = a; s.tone = tone; s.rgb[0] = r; s.rgb[1] = g; s.rgb[2] = b;
				s.logL = std::log10((std::max)(lum, 1e-30));
				src_.push_back(s);
				if (s.kind == Source::TOES) lastToes = (int)src_.size() - 1;
			}
			else if (std::sscanf(line, "SUBLIM %lf %lf %lf", &e, &n, &u) == 3)
			{
				Sublim s; s.pos = _V(e, u, n); s.light = lastToes; sub_.push_back(s);
			}
			else if (std::sscanf(line, "TOUCHDOWN %lf %lf %lf", &e, &n, &u) == 3) td_.push_back(_V(e, u, n));
			else if (std::sscanf(line, "PROBE %255s %lf %lf L17 %lf", name, &e, &n, &u) == 4) probes_.push_back({ name, e, n, u });
			else if (std::sscanf(line, "MESH %255s", name) == 1) meshName_ = name;
			else if (std::sscanf(line, "PLUME_MESH %255s", name) == 1) plumeMesh_ = name;
			else if (std::sscanf(line, "GLOW_GAIN %lf", &e) == 1) glowGain_ = e;
			else if (std::sscanf(line, "FOOTPRINT_MESH %255s", name) == 1) fpMesh_ = name;
			else if (std::sscanf(line, "SKIN_MESH %255s", name) == 1) skinMesh_ = name;
			else if (std::sscanf(line, "FOOTPRINT_PRM %d %lf %lf %lf", &gi, &e, &n, &u) == 4) { fpN_ = gi; fpAgeMax_ = e; fpThrLo_ = n; fpThrHi_ = u; }
			else if (std::sscanf(line, "PLUME_PRM %lf %lf %lf %lf", &e, &n, &u, &a) == 4) { pBase_ = e; pG_ = n; pKmax_ = u; pR_ = a; }
			else if (std::sscanf(line, "PLUME_BAND %d %lf %lf %lf %lf", &gi, &a, &e, &u, &n) == 5) pbands_.push_back({ gi, a, _V(e, u, n) });
			else if (std::sscanf(line, "GLOWGROUP %d %31s", &gi, kind) == 2)
				glow_.push_back({ gi, !std::strcmp(kind, "LAKE") ? 1 : !std::strcmp(kind, "SKYLIGHT") ? 2 : 0 });
		}
		std::fclose(f);
	}
};

