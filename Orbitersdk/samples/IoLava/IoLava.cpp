// IoLava.dll - live effects of the Io lava field (Prometheus, Tantra_Design/io_lava):
//  * the glowing lava itself: a thin additive, unlit mesh draped 0.3 m over the hottest ground (lobe toes and cracks,
//    the summit lava lake, the tube skylights) - planet terrain in D3D9Client can't be brighter than its albedo
//    (night lights are multiplied by it), a mesh can;
//  * the light the lava throws on whatever stands near it (the suit, its visor): point lights;
//  * their slow flicker as the crust tears, toes break out and the lake crust founders;
//  * SO2 frost sublimating where the lobe front overruns the plain: frost grains lit from below.
//
// The vessel IoLava\LavaField stands at ANCHOR of Config/Io/LavaField/Effects.cfg (generated by build.py effects /
// glowmesh). Its TOUCHDOWN points are ground points of the elevation tiles, so Orbiter rests it level
// (east-up-north) and the mesh lies on the terrain.
//
// Physics:
//  * a glowing patch of radius A and mean luminance L, seen from distance d on its axis, gives the illuminance
//    E = pi L A^2 / (A^2 + d^2): a point light with att0 = 1, att1 = 0, att2 = 1/A^2 is exactly that falloff;
//  * brightness: the log tone map of the Mask night lights (Draper point .. 1450 K), colour: the lava's blackbody;
//  * no air on Io (~1 nbar): no heat shimmer, no glow halo in the gas; sublimated gas leaves ballistically;
//  * flicker: log-luminance of each source wanders (Ornstein-Uhlenbeck) at the time scale of its process; breakouts /
//    lake overturns add a brightening that fades as the new skin cools. In sunlight the glow mesh is dimmed (to 25 % with the
//    Sun 20 deg up): only molten lava competes with Io's daylight.
