"""Ground-type raster of the Titan landing site for OrbiterCrew (suits) and MPU/EMPU (wheels):
Config/OrbiterCrew/Ground/Titan.cfg (text header) + Titan.bin (one byte per cell).

Classes come from the same terrain function as the surface tiles (gen_titan_site.fields), so what
is drawn and what is under foot/wheel agree:
  0 sand        - dark organic sand, damp and cohesive (Huygens site soil)
  1 cobbles     - rounded water-ice cobbles 5-15 cm on sand: river beds, valley floors, outwash fans
  2 ice bedrock - bare water-ice slopes and crests
  3 wet margin  - the first ~50 m of shore: saturated sand
  4 liquid      - methane/ethane sea surface
Grid: rows from north to south, columns from west to east, square cells StepM metres in the local
east/north frame around (CenterLat, CenterLon): x = R cos(CenterLat) dlon, y = R dlat, R = 2575 km.
Cell (row r, col c) centre: x = (c + 0.5) * StepM - W * StepM / 2, y = H * StepM / 2 - (r + 0.5) * StepM.

Usage: gen_titan_ground.py <orbiter root> <Titan_src folder> [step_m]
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_titan_site as s  # noqa: E402

NAMES = ["sand", "cobbles", "ice_bedrock", "wet_margin", "liquid"]


def build(root, src, step_m=50.0):
    s.load(os.path.join(s.HERE, "_titan_site_master_v3.npz"), src)
    half = s.HALF - 1.0                           # stay inside the master rasters
    n = int(round(2 * half * 1000 / step_m))
    step = 2 * half / n                           # km
    xs = (np.arange(n) + 0.5) * step - half
    out = np.zeros((n, n), np.uint8)
    rows = 256
    for r0 in range(0, n, rows):
        r1 = min(n, r0 + rows)
        ys = half - (np.arange(r0 - 1, r1 + 1) + 0.5) * step   # one extra row each side for gradients
        X, Y = np.meshgrid(xs, ys)
        lon, lat = s.to_lonlat(X, Y)
        _, _, _, ex = s.fields(lon, lat, step, extra=True)
        out[r0:r1] = ex["cls"][1:-1]
        print(f"rows {r0}-{r1} of {n}", flush=True)
    d = os.path.join(root, "Config", "OrbiterCrew", "Ground")
    os.makedirs(d, exist_ok=True)
    out.tofile(os.path.join(d, "Titan.bin"))
    counts = np.bincount(out.ravel(), minlength=5) / out.size * 100
    with open(os.path.join(d, "Titan.cfg"), "w", encoding="utf8") as f:
        f.write("; Ground types of the Titan landing site (southern Kraken Mare shore)\n")
        f.write("; Generated by Orbitersdk/samples/TitanSite/tools/gen_titan_ground.py from the surface-tile terrain.\n")
        f.write("; Titan.bin: W x H bytes, rows north to south, columns west to east, one class number per cell.\n")
        f.write("; Local frame: x = R*cos(CenterLat)*dLon (east), y = R*dLat (north), R = 2575 km.\n")
        f.write("Body = Titan\n")
        f.write(f"CenterLat = {s.LAT_C:.6f}\n")
        f.write(f"CenterLon = {s.LON_C:.6f}\n")
        f.write(f"StepM = {step * 1000:.4f}\n")
        f.write(f"W = {n}\nH = {n}\n")
        f.write(f"LiquidLevel = {s._M['level']:.2f}        ; m from the mean radius (2575 km): surface of the northern seas; depth = LiquidLevel - ground elevation\n")
        f.write("Classes = " + ", ".join(f"{i} {nm}" for i, nm in enumerate(NAMES)) + "\n")
        f.write("; share of the area: " + ", ".join(f"{nm} {c:.1f}%" for nm, c in zip(NAMES, counts)) + "\n")
    print("written", d, n, "x", n, "shares", counts.round(1), flush=True)


if __name__ == "__main__":
    build(sys.argv[1], sys.argv[2], float(sys.argv[3]) if len(sys.argv) > 3 else 50.0)
